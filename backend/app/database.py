from sqlalchemy import create_engine, Column, Integer, String, DateTime, Text, Boolean, ForeignKey, JSON
from sqlalchemy.ext.declarative import declarative_base
from sqlalchemy.orm import sessionmaker, relationship, Session
from sqlalchemy.sql import func
from datetime import datetime
from .config import settings

# Create SQLAlchemy engine
engine = create_engine(settings.database_url)

# Create SessionLocal class
SessionLocal = sessionmaker(autocommit=False, autoflush=False, bind=engine)

# Create Base class
Base = declarative_base()

# Database models
class User(Base):
    __tablename__ = "users"
    
    id = Column(Integer, primary_key=True, index=True)
    email = Column(String, unique=True, index=True, nullable=False)
    username = Column(String, unique=True, index=True, nullable=False)
    full_name = Column(String, nullable=False)
    hashed_password = Column(String, nullable=False)
    is_active = Column(Boolean, default=True)
    created_at = Column(DateTime(timezone=True), server_default=func.now())
    updated_at = Column(DateTime(timezone=True), onupdate=func.now())
    
    # Relationships
    tweets = relationship("SavedTweet", back_populates="user")

class TweetAuthorDB(Base):
    __tablename__ = "tweet_authors"
    
    id = Column(Integer, primary_key=True, index=True)
    twitter_id = Column(String, unique=True, index=True, nullable=False)  # Twitter's author ID
    name = Column(String, nullable=False)
    username = Column(String, nullable=False)
    profile_image_url = Column(String, nullable=True)
    public_metrics = Column(JSON, nullable=True)  # Store as JSON
    created_at = Column(DateTime(timezone=True), server_default=func.now())
    updated_at = Column(DateTime(timezone=True), onupdate=func.now())
    
    # Relationships
    tweets = relationship("SavedTweet", back_populates="author")

class SavedTweet(Base):
    __tablename__ = "saved_tweets"
    
    id = Column(Integer, primary_key=True, index=True)
    twitter_id = Column(String, unique=True, index=True, nullable=False)  # Twitter's tweet ID
    text = Column(Text, nullable=False)
    created_at_twitter = Column(DateTime(timezone=True), nullable=True)  # When tweet was created on Twitter
    public_metrics = Column(JSON, nullable=True)  # Store as JSON
    context_annotations = Column(JSON, nullable=True)  # Store as JSON
    source = Column(String, nullable=True)  # masa_api, twitter_api, etc.
    
    # Foreign keys
    user_id = Column(Integer, ForeignKey("users.id"), nullable=False)  # Who fetched this tweet
    author_id = Column(Integer, ForeignKey("tweet_authors.id"), nullable=False)  # Tweet author
    
    # Metadata
    created_at = Column(DateTime(timezone=True), server_default=func.now())  # When saved to our DB
    updated_at = Column(DateTime(timezone=True), onupdate=func.now())
    
    # Relationships
    user = relationship("User", back_populates="tweets")
    author = relationship("TweetAuthorDB", back_populates="tweets")
    analyses = relationship("TweetAnalysis", back_populates="tweet")

class TweetAnalysis(Base):
    __tablename__ = "tweet_analyses"
    
    id = Column(Integer, primary_key=True, index=True)
    
    # Analysis results from RunPod API
    predicted_label = Column(String, nullable=False)  # e.g., "postpartum"
    predicted_class_id = Column(Integer, nullable=False)  # e.g., 4
    confidence = Column(String, nullable=False)  # Store as string to preserve precision
    all_probabilities = Column(JSON, nullable=False)  # Store all category probabilities
    
    # Metadata
    analyzed_text = Column(Text, nullable=False)  # The text that was analyzed
    analysis_timestamp = Column(DateTime(timezone=True), server_default=func.now())
    
    # Foreign keys
    tweet_id = Column(Integer, ForeignKey("saved_tweets.id"), nullable=False)
    user_id = Column(Integer, ForeignKey("users.id"), nullable=False)  # Who requested the analysis
    
    # Relationships
    tweet = relationship("SavedTweet", back_populates="analyses")
    user = relationship("User")

class AnalysisReport(Base):
    __tablename__ = "analysis_reports"
    
    id = Column(Integer, primary_key=True, index=True)
    report_content = Column(Text, nullable=False)  # The full report generated by LiteLLM
    summary = Column(Text, nullable=False)  # Brief summary of the report
    total_analyzed_tweets = Column(Integer, nullable=False)
    classification_breakdown = Column(JSON, nullable=False)  # Count of each classification
    generated_at = Column(DateTime(timezone=True), server_default=func.now())
    
    # Foreign keys
    user_id = Column(Integer, ForeignKey("users.id"), nullable=False)
    
    # Relationships
    user = relationship("User")

# Dependency to get database session
def get_db():
    db = SessionLocal()
    try:
        yield db
    finally:
        db.close()

# Helper functions for tweet storage
def get_or_create_tweet_author(db: Session, author_data: dict) -> TweetAuthorDB:
    """Get existing or create new tweet author"""
    # Try to find existing author by Twitter ID
    author = db.query(TweetAuthorDB).filter(TweetAuthorDB.twitter_id == author_data['id']).first()
    
    if not author:
        # Create new author
        author = TweetAuthorDB(
            twitter_id=author_data['id'],
            name=author_data['name'],
            username=author_data['username'],
            profile_image_url=author_data.get('profile_image_url'),
            public_metrics=author_data.get('public_metrics')
        )
        db.add(author)
        db.commit()
        db.refresh(author)
    else:
        # Update existing author info (in case it changed)
        author.name = author_data['name']
        author.username = author_data['username']
        author.profile_image_url = author_data.get('profile_image_url')
        author.public_metrics = author_data.get('public_metrics')
        db.commit()
    
    return author

def get_cached_tweets_by_query(db: Session, query: str, user_id: int, max_results: int = 10) -> list:
    """Get cached tweets that match a search query for a specific user"""
    try:
        # For search queries, we'll look for tweets that contain the query terms
        # This is a simple text-based search - more sophisticated matching could be added
        
        # Clean up the query - remove special Twitter operators for basic text matching
        search_terms = query.lower()
        
        # Remove common Twitter operators to get basic search terms
        search_terms = search_terms.replace('from:', '').replace('#', '').replace('@', '')
        search_terms = search_terms.replace('"', '').strip()
        
        # If it's a user-specific query (from:username), handle it specially
        if 'from:' in query.lower():
            username = query.lower().replace('from:', '').strip()
            return get_cached_tweets_by_username(db, username, user_id, max_results)
        
        # Search for tweets that contain the search terms
        saved_tweets = db.query(SavedTweet).filter(
            SavedTweet.user_id == user_id,
            SavedTweet.text.ilike(f'%{search_terms}%')
        ).order_by(SavedTweet.created_at.desc()).limit(max_results * 2).all()  # Get extra to account for filtering
        
        return saved_tweets[:max_results]
        
    except Exception as e:
        print(f"Error getting cached tweets by query: {str(e)}")
        return []

def get_cached_tweets_by_username(db: Session, username: str, user_id: int, max_results: int = 10) -> list:
    """Get cached tweets from a specific Twitter username for a specific user"""
    try:
        # Clean username (remove @ if present)
        clean_username = username.lower().replace('@', '').strip()
        
        # Find tweets from this author
        saved_tweets = db.query(SavedTweet).join(TweetAuthorDB).filter(
            SavedTweet.user_id == user_id,
            TweetAuthorDB.username.ilike(clean_username)
        ).order_by(SavedTweet.created_at.desc()).limit(max_results).all()
        
        return saved_tweets
        
    except Exception as e:
        print(f"Error getting cached tweets by username: {str(e)}")
        return []

def save_tweet_to_db(db: Session, tweet_data: dict, user_id: int) -> SavedTweet:
    """Save a tweet to the database"""
    # Check if tweet already exists for this user
    existing_tweet = db.query(SavedTweet).filter(
        SavedTweet.twitter_id == tweet_data['id'],
        SavedTweet.user_id == user_id
    ).first()
    
    if existing_tweet:
        return existing_tweet
    
    # Get or create the tweet author
    author = get_or_create_tweet_author(db, tweet_data['author'])
    
    # Parse Twitter's created_at timestamp
    created_at_twitter = None
    if tweet_data.get('created_at'):
        try:
            # Handle different datetime formats from Twitter/Masa API
            from datetime import datetime
            import dateutil.parser
            created_at_twitter = dateutil.parser.parse(tweet_data['created_at'])
        except:
            created_at_twitter = None
    
    # Create new saved tweet
    saved_tweet = SavedTweet(
        twitter_id=tweet_data['id'],
        text=tweet_data['text'],
        created_at_twitter=created_at_twitter,
        public_metrics=tweet_data.get('public_metrics'),
        context_annotations=tweet_data.get('context_annotations'),
        source=tweet_data.get('source', 'unknown'),
        user_id=user_id,
        author_id=author.id
    )
    
    db.add(saved_tweet)
    db.commit()
    db.refresh(saved_tweet)
    
    return saved_tweet

def save_tweets_to_db(db: Session, tweets_data: list, user_id: int) -> list:
    """Save multiple tweets to the database"""
    saved_tweets = []
    for tweet_data in tweets_data:
        try:
            saved_tweet = save_tweet_to_db(db, tweet_data, user_id)
            saved_tweets.append(saved_tweet)
        except Exception as e:
            print(f"Failed to save tweet {tweet_data.get('id', 'unknown')}: {str(e)}")
            continue
    
    return saved_tweets

# Create all tables
def create_tables():
    Base.metadata.create_all(bind=engine)

def get_database_url():
    """Get the database URL from settings"""
    return settings.database_url 